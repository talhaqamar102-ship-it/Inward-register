// Usage: node scripts/gen-main-map.mjs [dir-or-file ...] > MAIN_MAP.md   (default: src)
// Maps every top-level function / window.* handler in every .ts file under the
// given paths, so an AI can open ONLY the line range it needs. Big functions
// (>250 lines) also get an inner index of nested functions and `// ---` banners.
import { readFileSync, readdirSync, statSync } from 'node:fs';
import { join } from 'node:path';

const BIG = Number(process.env.BIG || 250);
const roots = process.argv.slice(2);
if (roots.length === 0) roots.push('src');

function walk(p, acc = []) {
  if (statSync(p).isDirectory()) {
    for (const f of readdirSync(p).sort()) {
      if (f === 'node_modules' || f.startsWith('.')) continue;
      walk(join(p, f), acc);
    }
  } else if (/\.ts$/.test(p) && !/\.d\.ts$/.test(p) && !/\.(test|spec)\.ts$/.test(p)) {
    acc.push(p);
  }
  return acc;
}

const files = roots.flatMap(r => walk(r));
const out = [
  '# MAIN_MAP — generated by scripts/gen-main-map.mjs, do not hand-edit',
  '',
  'Find the file + line range here, then open only that slice: `sed -n START,ENDp FILE`.',
  'Never read a whole file over ~500 lines.',
  '',
];

const summary = [];
const sections = [];

for (const file of files) {
  const lines = readFileSync(file, 'utf8').split('\n');
  const starts = [];
  lines.forEach((l, i) => {
    let m;
    if ((m = l.match(/^(?:export )?(?:async )?function (\w+)/))) starts.push({ i, name: m[1], kind: 'fn' });
    else if ((m = l.match(/^window\.(\w+)\s*=/))) starts.push({ i, name: `window.${m[1]}`, kind: 'window' });
    else if ((m = l.match(/^(?:export )?const (\w+)\s*=\s*(?:async\s*)?(?:\([^)]*\)|\w+)\s*(?::[^=]+)?=>/))) starts.push({ i, name: m[1], kind: 'fn' });
  });
  if (starts.length === 0) continue;

  const rows = [];
  for (const s of starts) {
    let end = s.i;
    const first = lines[s.i];
    const bal = (first.match(/[{(\[]/g) || []).length === (first.match(/[})\]]/g) || []).length;
    const oneLiner = bal && /(=>|\bfunction\b)/.test(first) && /[;})]\s*$/.test(first) && !/[{(]\s*$/.test(first);
    if (!oneLiner) {
      end = s.i + 1;
      while (end < lines.length && !/^[}\)];?\s*$/.test(lines[end])) end++;
    }
    const nextStart = starts.find(t => t.i > s.i);
    if (nextStart && end >= nextStart.i) end = nextStart.i - 1;
    const size = end - s.i + 1;
    rows.push(`| ${s.i + 1}–${end + 1} | ${size} | ${s.kind} | \`${s.name}\` |`);
    if (size > BIG) {
      const inner = [];
      for (let k = s.i + 1; k < end; k++) {
        let m;
        if ((m = lines[k].match(/^  window\.(\w+)\s*=/))) inner.push(`|   ↳ ${k + 1} | | window | \`window.${m[1]}\` |`);
        else if ((m = lines[k].match(/^  (?:async )?function (\w+)/))) inner.push(`|   ↳ ${k + 1} | | inner fn | \`${m[1]}\` |`);
        else if ((m = lines[k].match(/^  \/\/\s*[-=─━#]{2,}\s*(.+?)\s*[-=─━#]*\s*$/))) inner.push(`|   ↳ ${k + 1} | | section | ${m[1]} |`);
      }
      rows.push(...inner);
    }
  }
  summary.push(`| \`${file}\` | ${lines.length} |`);
  sections.push(`## ${file} (${lines.length} lines)`, '', '| Lines | Size | Kind | Name |', '|---|---:|---|---|', ...rows, '');
}

out.push('## Files', '', '| File | Lines |', '|---|---:|', ...summary, '', ...sections);
console.log(out.join('\n'));
